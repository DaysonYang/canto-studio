const assert = require('node:assert/strict');
require('../data/dictionary.js');
require('../data/variants.js');
require('../variants.js');
require('../engine.js');
require('../data/corpus.js');
require('../data/clauses.js');
require('../quality.js');
require('../pos.js');
require('../ranking.js');
require('../sentence.js');
require('../compose-engine.js');

(async () => {
  const core = CantoComposeEngine;
  const strict = CantoEngine.ENCODING_MODES['394052'];
  const loose = CantoEngine.ENCODING_MODES['0243'];
  const strictIndex = CantoEngine.createIndex(CANTO_DATA,strict);
  const looseIndex = CantoEngine.createIndex(CANTO_DATA,loose);
  const search = (code,mapping = strict)=>({code,mapping,found:CantoEngine.search(mapping===strict?strictIndex:looseIndex,code)});
  const main = search('0033994');
  const suggestions = core.suggestions(main.code,main.found);
  assert.equal(suggestions[0],'00 + 33 + 99 + 4');
  for (const suggestion of ['003 + 399 + 4','0033 + 994','00 + 339 + 94']) assert(suggestions.includes(suggestion));
  const slots = core.slotsFor(core.parse(main.code,suggestions[0]));
  assert.throws(()=>core.parse(main.code,'00+33+4+99'));
  assert.throws(()=>core.parse(main.code,'00++33994'));
  const comparisons = [];
  for (const [position,slot] of slots.entries()) {
    const open = core.filtered(main,slot);
    assert(open.length > 0);
    assert(open.slice(0,20).every(entry=>core.valid(main,slot,entry)));
    const noun = core.filtered(main,{...slot,pos:['noun']});
    const verb = core.filtered(main,{...slot,pos:['verb']});
    assert(noun.length > 0 && noun.length < open.length);
    assert(verb.length > 0 && verb.length < open.length);
    assert(noun.every(entry=>CantoPOS.tags(entry.word).includes('noun')));
    assert(verb.every(entry=>CantoPOS.tags(entry.word).includes('verb')));
    assert.equal(core.filtered(main,{...slot,pos:['noun','verb']}).length,new Set([...noun,...verb]).size);
    const ranking = core.rank(main,slot,slots,'',false);
    comparisons.push({slot:slot.code,top:ranking.slice(0,3).map(entry=>entry.word)});
    assert.equal(slots[position].pos.length,0);
  }
  assert(Object.keys(CANTO_CORPUS.words).some(word=>CantoPOS.tags(word).length>1));
  const timeWord = core.filtered(main,{...slots[0],query:'平時'}).find(entry=>entry.word==='平時');
  assert(timeWord);
  slots[0].selected=timeWord;
  slots[0].locked=true;
  const revised=core.slotsFor(core.parse(main.code,'00+339+94'),slots);
  assert.equal(revised[0].selected,timeWord);
  assert(revised[0].locked);
  assert.equal(revised[1].selected,null);
  const baseline = core.rank(main,slots[1],slots,'',false).slice(0,12);
  const dynamic = core.rank(main,slots[1],slots,'',true).slice(0,12);
  assert.notDeepEqual(dynamic.map(entry=>entry.word),baseline.map(entry=>entry.word));
  assert(dynamic.every(entry=>core.valid(main,slots[1],entry)));
  const single = search('4');
  const particle = {...core.slotsFor(['4'])[0],pos:['particle']};
  const particles=core.rank(single,particle,[particle],'',false);
  assert(particles.length>2 && particles.every(entry=>CantoPOS.tags(entry.word).includes('particle')));
  const all = core.rank(single,core.slotsFor(['4'])[0],[],'',false);
  assert(all.slice(0,10).filter(entry=>CantoPOS.tags(entry.word).includes('particle')).length<=2);
  assert.equal(search('0033994',loose).found.ways,0n);
  const looseSlot=core.slotsFor(['4'])[0];
  const fifth=core.filtered(search('4',loose),looseSlot).find(entry=>entry.word==='市' && entry.reading==='si5');
  assert(fifth && !core.valid(single,looseSlot,fifth));
  const recommendationContext=search('532434');
  const parts=['53','2','4','3','4'];
  const picks=core.slotsFor(parts);
  picks[0].selected=core.filtered(recommendationContext,{...picks[0],query:'已經'}).find(entry=>entry.word==='已經');
  assert(picks[0].selected);
  picks[0].locked=true;
  picks[1].query='換';
  const graph=core.recommendationGraph(recommendationContext,picks);
  const ranked=await CantoSentence.retrieve(graph,{modes:{natural:true,theme:true},theme:'換衫',weights:CantoRank.DEFAULT_WEIGHTS,style:'lyrics'},parts,()=>false,recommendationContext);
  assert(ranked.items.some(item=>item.word==='已經換晒衫嚹'));
  assert(ranked.items.every(item=>core.same(item.entries[0],picks[0].selected) && item.entries[1].word.includes('換')));
  assert(core.apply(recommendationContext,picks,ranked.items[0].entries));
  const before=picks.map(slot=>slot.selected.word);
  assert(!core.apply(recommendationContext,picks,[...ranked.items[0].entries].reverse()));
  assert.deepEqual(picks.map(slot=>slot.selected.word),before);
  for (const code of ['3','00','0033994','5034222904','559943294432']) {
    const context=search(code);
    const choice=core.suggestions(code,context.found)[0];
    assert(choice);
    for (const slot of core.slotsFor(core.parse(code,choice))) assert(core.valid(context,slot,core.entries(context,slot)[0]));
  }
  console.log('PASS: 真實詞性多選、獨立槽、聲調／字數、保留已選、動態排序、鎖定推薦、兩套編碼及 1–12 字');
  console.log(JSON.stringify({comparisons,without:baseline.slice(0,4).map(entry=>entry.word),with:dynamic.slice(0,4).map(entry=>entry.word),recommended:ranked.items[0].word}));
})().catch(error=>{console.error(error);process.exitCode=1;});
